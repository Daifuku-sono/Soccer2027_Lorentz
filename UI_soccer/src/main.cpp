uint16_t getAutoRainbowColor()
{
  // マイコンの起動からの時間(ms)を利用して自動で変化させる
  // 割り算の数値（ここでは 5）を変更すると、色の変わるスピードを調整できます
  // 数値を小さくすると速く、大きくするとゆっくり変化します
  unsigned long ms = millis();
  uint8_t pos = (ms / 5) % 256;

  int zone = (pos * 6) / 256;
  int rem = (pos * 6) % 256;

  uint16_t r = 0, g = 0, b = 0;

  switch (zone)
  {
  case 0: // 赤 → 黄
    r = 31;
    g = (rem * 63) / 255;
    b = 0;
    break;
  case 1: // 黄 → 緑
    r = ((255 - rem) * 31) / 255;
    g = 63;
    b = 0;
    break;
  case 2: // 緑 → シアン
    r = 0;
    g = 63;
    b = (rem * 31) / 255;
    break;
  case 3: // シアン → 青
    r = 0;
    g = ((255 - rem) * 63) / 255;
    b = 31;
    break;
  case 4: // 青 → マゼンタ
    r = (rem * 31) / 255;
    g = 0;
    b = 31;
    break;
  case 5: // マゼンタ → 赤
    r = 31;
    g = 0;
    b = ((255 - rem) * 31) / 255;
    break;
  }

  // RGB565の形式にパックして返す
  return (r << 11) | (g << 5) | b;
}

void setmode()
{
  static int page = 0;
  static int mode = 0;
  int maxpage[itemCount] = {2, 2, 3, 3, 2, 2, 2, 2, 2};
  for (int i = 0; i < itemCount; i++)
  {
    // Serial.println(maxpage[i]);
  }
  if (page == 0)
  {
    // 上ボタン
    if (digitalRead(0) == HIGH)
    {
      delay(50);
      while (digitalRead(0) == HIGH)
      {
      }
      delay(50);
      currentIndex = (currentIndex + 1) % itemCount;
    }
    // 下ボタン（ピン2）
    if (digitalRead(2) == HIGH)
    {
      delay(50);
      while (digitalRead(2) == HIGH)
      {
      }
      delay(50);
      currentIndex = (currentIndex - 1 + itemCount) % itemCount;
    }

    spr.fillSprite(TFT_BLACK);

    print(20, 12, "Lorentz Menu", 2, TFT_CYAN, TFT_BLACK);
    spr.drawFastHLine(0, 35, 240, TFT_DARKGREY); // 区切り線

    // --- スクロール位置（topIndex）の滑らかな追従管理 ---
    static int topIndex = 0;

    if (currentIndex < topIndex)
    {
      topIndex = currentIndex;
    }
    else if (currentIndex >= topIndex + visibleItems)
    {
      topIndex = currentIndex - visibleItems + 1;
    }
    if (currentIndex == 0)
    {
      topIndex = 0;
    }
    else if (currentIndex == itemCount - 1)
    {
      topIndex = itemCount - visibleItems;
      if (topIndex < 0)
        topIndex = 0;
    }

    for (int i = 0; i < visibleItems; i++)
    {
      int itemIdx = topIndex + i;
      if (itemIdx < itemCount)
      {
        int y = startY + (i * itemHeight);

        if (itemIdx == currentIndex)
        {
          spr.fillRect(15, y - 9, 200, itemHeight, TFT_CYAN);
          print(20, y, menuItems[itemIdx], 3, TFT_BLACK, TFT_CYAN);
        }
        else
        {
          print(20, y, menuItems[itemIdx], 3, TFT_WHITE, TFT_BLACK);
        }
      }
    }

    // 決定ボタン（ピン1）でページを切り替える
    if (digitalRead(1) == HIGH)
    {
      delay(50);
      while (digitalRead(1) == HIGH)
      {
      }
      delay(50);

      page = 1;
      mode = currentIndex; // 選択しているインデックスをそのままモード番号にする
    }
  }
  else if (page == 1)
  {
    if (digitalRead(1) == HIGH)
    {
      delay(50);
      while (digitalRead(1) == HIGH)
      {
      }
      delay(50);
      page++;
      page = page % maxpage[mode];
    }
    else
    {
      // 各モードの実行（mode 番号で自動振り分け）
      if (mode == 0)
      {
        zikoichi();
      }
      else if (mode == 1)
      {
        ball();
      }
      else if (mode == 2)
      {
        line();
      }
      else if (mode == 3)
      {
        Maincam();
      }
      else if (mode == 4)
      {
        drawBitmap(0, 0, epd_bitmap_image, 240, 240, getAutoRainbowColor());
      }
      else if (mode == 5)
      {
        BLE();
      }
      else if (mode == 6)
      {
        drawBitmap(0, 0, epd_bitmap_image, 240, 240, getAutoRainbowColor());
      }
      else if (mode == 7)
      {
        drawBitmap(0, 0, epd_bitmap_image, 240, 240, getAutoRainbowColor());
      }
      else if (mode == 8)
      {
        drawBitmap(0, 0, epd_bitmap_image, 240, 240, getAutoRainbowColor());
      }
    }
  }
  else if (page == 2)
  {
    if (digitalRead(1) == HIGH)
    {
      delay(50);
      while (digitalRead(1) == HIGH)
      {
      }
      delay(50);
      page++;
      page = page % maxpage[mode];
    }
    else
    {
      if (mode == 2)
      {
        linedebug();
      }
      if (mode == 3)
      {
        Maincamdebug();
      }
    }
  }
  spr.pushSprite(0, 0);
}


uint16_t getAutoRainbowColor()
{
  // マイコンの起動からの時間(ms)を利用して自動で変化させる
  // 割り算の数値（ここでは 5）を変更すると、色の変わるスピードを調整できます
  // 数値を小さくすると速く、大きくするとゆっくり変化します
  unsigned long ms = millis();
  uint8_t pos = (ms / 5) % 256;

  int zone = (pos * 6) / 256;
  int rem = (pos * 6) % 256;

  uint16_t r = 0, g = 0, b = 0;

  switch (zone)
  {
  case 0: // 赤 → 黄
    r = 31;
    g = (rem * 63) / 255;
    b = 0;
    break;
  case 1: // 黄 → 緑
    r = ((255 - rem) * 31) / 255;
    g = 63;
    b = 0;
    break;
  case 2: // 緑 → シアン
    r = 0;
    g = 63;
    b = (rem * 31) / 255;
    break;
  case 3: // シアン → 青
    r = 0;
    g = ((255 - rem) * 63) / 255;
    b = 31;
    break;
  case 4: // 青 → マゼンタ
    r = (rem * 31) / 255;
    g = 0;
    b = 31;
    break;
  case 5: // マゼンタ → 赤
    r = 31;
    g = 0;
    b = ((255 - rem) * 31) / 255;
    break;
  }

  // RGB565の形式にパックして返す
  return (r << 11) | (g << 5) | b;
}

